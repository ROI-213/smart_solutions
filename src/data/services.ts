export const findService = (slug: string) => services.find((s) => s.slug === slug);

export const slugifyItem = (name: string) =>
  name
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

export type ServiceItemMatch = { item: string; itemSlug: string; category: Service };

export const findServiceItem = (slug: string): ServiceItemMatch | undefined => {
  for (const category of services) {
    for (const item of category.items) {
      if (slugifyItem(item) === slug) return { item, itemSlug: slug, category };
    }
  }
  return undefined;
};
